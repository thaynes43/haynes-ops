#!/usr/bin/env python3
"""Render Cursor project rules and a staged MCP manifest without reading secrets.

No MCP process is started here. Activation is a separate, explicitly approved step.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

# Override only for offline fixtures; production reads the mounted shared config.
CONFIG = Path(os.environ.get('DEV_ENV_CLAUDE_CONFIG', '/opt/dev-env/config/claude'))
SCRIPTS = Path('/opt/dev-env/scripts')
MARKER = 'Generated by dev-env cursor-config.py; do not edit this file.'


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.cursor-config-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def render(workspace, source=CONFIG, scripts=SCRIPTS):
    common = (source / 'CLAUDE.md').read_text()
    specs = json.loads((source / 'mcp.json').read_text())['mcpServers']
    rules = workspace / '.cursor/rules/dev-env-shared.mdc'
    content = ('---\ndescription: Shared dev-env operating rules\nalwaysApply: true\n---\n'
               f'<!-- {MARKER} -->\n'
               'These are the shared pod rules. Also read repository CLAUDE.md and '
               'applicable AGENTS.md before work. Provider-specific commands describe '
               'those providers; do not claim unavailable Cursor capabilities.\n\n' + common)
    if rules.exists() and MARKER not in rules.read_text():
        raise ValueError('refusing to replace unmanaged project rules')
    # All transports are commands. URL MCPs on a My Machines worker otherwise run
    # from Cursor's backend and cannot reach the pod's private cluster endpoints.
    manifest = {'mcpServers': {name: {
        'command': '/usr/bin/env',
        'args': ['bash', str(scripts / 'cursor-mcp.sh'), name],
    } for name in specs}}
    pending = workspace / '.cursor/dev-env-mcp.pending.json'
    receipt = {
        'common_rules_sha256': hashlib.sha256(common.encode()).hexdigest(),
        'mcp_source_sha256': hashlib.sha256((source / 'mcp.json').read_bytes()).hexdigest(),
        'servers': sorted(specs), 'mcp_activation': 'pending',
        'worker_tool_parity': 'unverified', 'provider_native_features': 'not_portable',
    }
    atomic_write(rules, content)
    atomic_write(pending, json.dumps(manifest, indent=2) + '\n')
    atomic_write(workspace / '.cursor/dev-env-parity.json', json.dumps(receipt, indent=2) + '\n')
    # This is a local anchor integration, not repository content to commit.
    # The common exclude also keeps generated files out of its task worktrees.
    exclude = subprocess.check_output(['git', '-C', str(workspace), 'rev-parse',
                                      '--git-path', 'info/exclude'], text=True).strip()
    exclude = Path(exclude) if Path(exclude).is_absolute() else workspace / exclude
    exclude.parent.mkdir(parents=True, exist_ok=True)
    previous = exclude.read_text() if exclude.exists() else ''
    patterns = ['/.cursor/rules/dev-env-shared.mdc', '/.cursor/dev-env-mcp.pending.json',
                '/.cursor/dev-env-parity.json']
    additions = [x for x in patterns if x not in previous.splitlines()]
    if additions:
        atomic_write(exclude, previous.rstrip() + '\n' + '\n'.join(additions) + '\n')
    return receipt


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--workspace', required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(render(args.workspace), indent=2))
